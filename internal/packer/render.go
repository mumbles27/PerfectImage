// VarsFile is the generated variables file. Packer loads *.auto.pkrvars.hcl
// automatically; it is written with mode 0600 and never contains secrets
// (the build password and Proxmox credentials travel in the environment).
const VarsFile = "perfectimage.auto.pkrvars.hcl"

// AppsDir is where generated app scripts are written inside the workdir.
const AppsDir = "perfectimage/apps"

// Var is one generated Packer variable.
type Var struct {
	Name  string
	Value any // string, int or bool
}

// Vars builds the standard variable set every catalog image declares (see
// docs/packer.md) from an image, a request and the resolved credentials.
func Vars(img *catalog.Image, req BuildRequest, insecure bool, description string) []Var {
	r := img.Resources
	pick := func(override, def string) string {
		if override != "" {
			return override
		}
		return def
	}
	pickInt := func(override, def int) int {
		if override > 0 {
			return override
		}
		return def
	}
	tags := []string{"perfectimage"}
	for _, t := range img.Tags {
		if t != "perfectimage" {
			tags = append(tags, t)
		}
	}
	vars := []Var{
		{"proxmox_node", req.Node},
		{"proxmox_insecure", insecure},
		{"vm_id", req.VMID},
		{"template_name", req.TemplateName},
		{"template_description", description},
		{"tags", strings.Join(tags, ";")},
		{"cores", pickInt(req.Cores, r.Cores)},
		{"memory", pickInt(req.Memory, r.Memory)},
		{"disk_size", pick(req.Disk, r.Disk)},
		{"storage_pool", pick(req.Storage, r.Storage)},
		{"bridge", pick(req.Bridge, r.Bridge)},
		{"iso_storage_pool", pick(req.ISOStorage, "local")},
	}
	isoFile := pick(req.ISOFile, img.ISO.File)
	vars = append(vars, Var{"iso_file", isoFile})
	if isoFile == "" {
		vars = append(vars, Var{"iso_url", img.ISO.URL}, Var{"iso_checksum", img.ISO.Checksum})
	}
	if img.OSFamily == catalog.Windows {
		vars = append(vars, Var{"virtio_iso_file", pick(req.VirtioISOFile, img.ISO.VirtioFile)})
	}
	return vars
}

// hclString quotes s as an HCL string literal, escaping template sequences.
func hclString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\\':
			b.WriteString(`\\`)
		case c == '"':
			b.WriteString(`\"`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\r':
			b.WriteString(`\r`)
		case c == '\t':
			b.WriteString(`\t`)
		case (c == '$' || c == '%') && i+1 < len(s) && s[i+1] == '{':
			b.WriteByte(c)
			b.WriteByte(c)
		case c < 0x20:
			fmt.Fprintf(&b, `\u%04x`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// VarsHCL renders variables as a pkrvars file.
func VarsHCL(vars []Var) []byte {
	var b bytes.Buffer
	b.WriteString("# Generated by PerfectImage. Do not edit; secrets are passed via the environment.\n")
	width := 0
	for _, v := range vars {
		width = max(width, len(v.Name))
	}
	for _, v := range vars {
		var val string
		switch x := v.Value.(type) {
		case string:
			val = hclString(x)
		case int:
			val = strconv.Itoa(x)
		case bool:
			val = strconv.FormatBool(x)
		default:
			val = hclString(fmt.Sprint(x))
		}
		fmt.Fprintf(&b, "%-*s = %s\n", width, v.Name, val)
	}
	return b.Bytes()
}

var unsafeName = regexp.MustCompile(`[^a-z0-9._-]+`)

func stepFile(i int, s catalog.InstallStep) string {
	ext := ".sh"
	if s.Shell == catalog.ShellPowerShell {
		ext = ".ps1"
	}
	return fmt.Sprintf("%02d-%s%s", i+1, unsafeName.ReplaceAllString(strings.ToLower(s.AppID), "_"), ext)
}

// Provisioners renders the HCL provisioner blocks that replace the apps
// marker. Each step runs as its own provisioner so the build log shows
// which app failed. Windows steps that need a reboot are followed by a
// windows-restart provisioner; Linux ones by a reboot that packer
// reconnects after.
func Provisioners(family catalog.OSFamily, steps []catalog.InstallStep, indent string) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, indent+format+"\n", a...) }
	w("# BEGIN PerfectImage apps (generated: %d step(s))", len(steps))
	for i, s := range steps {
		script := "${path.root}/" + path.Join(AppsDir, stepFile(i, s))
		if family == catalog.Windows {
			w("provisioner %q {", "powershell")
			w("  # %s (%s)", oneLine(s.Name), s.AppID)
			w("  script = \"%s\"", script)
			w("}")
			if s.RebootRequired {
				w("provisioner %q {", "windows-restart")
				w("  restart_timeout = %q", "30m")
				w("}")
			}
			continue
		}
		w("provisioner %q {", "shell")
		w("  # %s (%s)", oneLine(s.Name), s.AppID)
		w("  execute_command = %q", "{{ .Vars }} sudo -E bash '{{ .Path }}'")
		w("  script          = \"%s\"", script)
		w("}")
		if s.RebootRequired {
			w("provisioner %q {", "shell")
			w("  # reboot required by %s", s.AppID)
			w("  execute_command   = %q", "{{ .Vars }} sudo -E bash '{{ .Path }}'")
			w("  inline            = [%q]", "systemctl reboot")
			w("  expect_disconnect = true")
			w("}")
			w("provisioner %q {", "shell")
			w("  pause_before = %q", "60s")
			w("  inline       = [%q]", "echo reconnected after reboot")
			w("}")
		}
	}
	w("# END PerfectImage apps")
	return strings.TrimSuffix(b.String(), "\n")
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// Render writes a build workdir: a copy of the image directory, the app
// scripts, the build file with the apps marker replaced and the variables
// file. dir must not exist or be empty.
func Render(dir string, img *catalog.Image, steps []catalog.InstallStep, vars []Var) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	err := fs.WalkDir(img.Files, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		dst := filepath.Join(dir, filepath.FromSlash(p))
		if d.IsDir() {
			return os.MkdirAll(dst, 0o700)
		}
		if !d.Type().IsRegular() {
			return nil
		}
		b, err := fs.ReadFile(img.Files, p)
		if err != nil {
			return err
		}
		return os.WriteFile(dst, b, 0o600)
	})
	if err != nil {
		return fmt.Errorf("copy image files: %w", err)
	}

	appsDir := filepath.Join(dir, filepath.FromSlash(AppsDir))
	if err := os.MkdirAll(appsDir, 0o700); err != nil {
		return err
	}
	for i, s := range steps {
		body := s.Script
		if s.Shell == catalog.ShellPowerShell {
			// Windows PowerShell 5.1 reads BOM-less files as ANSI.
			body = "\ufeff" + strings.ReplaceAll(body, "\n", "\r\n")
		}
		if err := os.WriteFile(filepath.Join(appsDir, stepFile(i, s)), []byte(body), 0o600); err != nil {
			return err
		}
	}

	buildPath := filepath.Join(dir, "build.pkr.hcl")
	b, err := os.ReadFile(buildPath)
	if err != nil {
		return fmt.Errorf("read build.pkr.hcl: %w", err)
	}
	out, err := injectProvisioners(b, img.OSFamily, steps)
	if err != nil {
		return err
	}
	if err := os.WriteFile(buildPath, out, 0o600); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, VarsFile), VarsHCL(vars), 0o600)
}

func injectProvisioners(build []byte, family catalog.OSFamily, steps []catalog.InstallStep) ([]byte, error) {
	lines := strings.Split(string(build), "\n")
	found := -1
	for i, l := range lines {
		if strings.TrimSpace(l) == catalog.AppsMarker {
			if found >= 0 {
				return nil, fmt.Errorf("build.pkr.hcl: %q appears more than once", catalog.AppsMarker)
			}
			found = i
		}
	}
	if found < 0 {
		return nil, fmt.Errorf("build.pkr.hcl: missing %q line", catalog.AppsMarker)
	}
	l := lines[found]
	indent := l[:len(l)-len(strings.TrimLeft(l, " \t"))]
	lines[found] = Provisioners(family, steps, indent)
	return []byte(strings.Join(lines, "\n")), nil
}
