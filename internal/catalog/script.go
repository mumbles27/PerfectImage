package catalog

import (
	"encoding/base64"
	"fmt"
	"strings"
	"unicode/utf16"
)

// shQuote quotes s for POSIX shells.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// psQuote quotes s as a PowerShell single-quoted string.
func psQuote(s string) string {
	// PowerShell also treats the typographic quotes as quote characters.
	r := strings.NewReplacer("'", "''", "‘", "‘‘", "’", "’’",
		"‚", "‚‚", "‛", "‛‛")
	return "'" + r.Replace(s) + "'"
}

// psEncode returns s as a base64 UTF-16LE string for powershell -EncodedCommand.
func psEncode(s string) string {
	u := utf16.Encode([]rune(s))
	b := make([]byte, 0, len(u)*2)
	for _, c := range u {
		b = append(b, byte(c), byte(c>>8))
	}
	return base64.StdEncoding.EncodeToString(b)
}

func uniqueVerifies(methods []Method) []string {
	var out []string
	seen := map[string]bool{}
	for _, m := range methods {
		v := strings.TrimSpace(m.Verify)
		if v != "" && !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}

// ---- bash ----

const bashPrelude = `#!/usr/bin/env bash
# Generated by PerfectImage from the app catalog. Runs as root.
set -u
export DEBIAN_FRONTEND=noninteractive
pi_verify() { bash -c "$1" >/dev/null 2>&1; }
pi_need() {
  # pi_need <command> <package>: install a helper tool with the distro package manager.
  command -v "$1" >/dev/null 2>&1 && return 0
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update -q && apt-get install -y -q "$2"
  elif command -v dnf >/dev/null 2>&1; then
    dnf -y install "$2"
  else
    echo "cannot install $2: no apt-get or dnf" >&2; return 1
  fi
}
export -f pi_need
`

func bashInstall(a *App, methods []Method) string {
	var b strings.Builder
	b.WriteString(bashPrelude)
	fmt.Fprintf(&b, "# App: %s (%s)\n", oneLine(a.Name), a.ID)
	tag := "[" + a.ID + "]"
	verifies := uniqueVerifies(methods)
	if len(verifies) > 0 {
		b.WriteString("if")
		for i, v := range verifies {
			if i > 0 {
				b.WriteString(" ||")
			}
			fmt.Fprintf(&b, " pi_verify %s", shQuote(v))
		}
		fmt.Fprintf(&b, "; then\n  echo %s\n  exit 0\nfi\n", shQuote("==> "+tag+" already installed"))
	}
	for i, m := range methods {
		label := fmt.Sprintf("%s method %d/%d (%s)", tag, i+1, len(methods), m.Kind())
		fmt.Fprintf(&b, "\necho %s\n", shQuote("==> "+label))
		fmt.Fprintf(&b, "if bash -eo pipefail -c %s; then\n", shQuote(bashMethod(m)))
		fmt.Fprintf(&b, "  if bash -c %s; then\n", shQuote(strings.TrimSpace(m.Verify)))
		fmt.Fprintf(&b, "    echo %s\n    exit 0\n  fi\n", shQuote("==> "+tag+" installed via "+m.Kind()))
		fmt.Fprintf(&b, "  echo %s >&2\n", shQuote("==> "+label+": verify failed"))
		fmt.Fprintf(&b, "else\n  echo %s >&2\nfi\n", shQuote("==> "+label+": install failed"))
	}
	fmt.Fprintf(&b, "\necho %s >&2\nexit 1\n", shQuote("==> "+tag+" all install methods failed"))
	return b.String()
}

func bashVerify(methods []Method) string {
	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n# Exits 0 when the app is installed.\n")
	for _, v := range uniqueVerifies(methods) {
		fmt.Fprintf(&b, "bash -c %s && exit 0\n", shQuote(v))
	}
	b.WriteString("exit 1\n")
	return b.String()
}

func bashMethod(m Method) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	switch m.Kind() {
	case "apt":
		if r := m.Apt.Repo; r != nil {
			key := "/etc/apt/keyrings/" + r.Name + ".gpg"
			w("pi_need curl curl; pi_need gpg gnupg")
			w("install -d -m 0755 /etc/apt/keyrings")
			w("tmp=$(mktemp)")
			w("curl -fsSL -o \"$tmp\" %s", shQuote(r.KeyURL))
			w("if grep -q 'BEGIN PGP' \"$tmp\"; then gpg --dearmor --yes -o %s \"$tmp\"; else install -m 0644 \"$tmp\" %s; fi", shQuote(key), shQuote(key))
			w("chmod 0644 %s; rm -f \"$tmp\"", shQuote(key))
			w("codename=$(. /etc/os-release && echo \"${VERSION_CODENAME:-}\")")
			// URL, suite and components are validated to a quote-free alphabet;
			// only $codename expands inside the double quotes.
			line := strings.TrimSpace(fmt.Sprintf("deb [signed-by=%s] %s %s %s", key, r.URL,
				strings.ReplaceAll(r.Suite, "{codename}", "${codename}"), r.Components))
			w("echo \"%s\" > %s", line, shQuote("/etc/apt/sources.list.d/"+r.Name+".list"))
		}
		w("apt-get update -q")
		w("apt-get install -y -q %s", quoteAll(m.Apt.Packages))
	case "dnf":
		if r := m.Dnf.Repo; r != nil {
			w("cat > %s <<'PI_REPO_EOF'", shQuote("/etc/yum.repos.d/"+r.Name+".repo"))
			w("[%s]\nname=%s\nbaseurl=%s\nenabled=1\ngpgcheck=1\ngpgkey=%s", r.Name, r.Name, r.URL, r.KeyURL)
			w("PI_REPO_EOF")
			w("rpm --import %s", shQuote(r.KeyURL))
		}
		w("dnf -y install %s", quoteAll(m.Dnf.Packages))
	case "snap":
		w("if ! command -v snap >/dev/null 2>&1; then")
		w("  if command -v apt-get >/dev/null 2>&1; then apt-get update -q && apt-get install -y -q snapd; else dnf -y install epel-release && dnf -y install snapd; fi")
		w("  systemctl enable --now snapd.socket")
		w("  [ -e /snap ] || ln -s /var/lib/snapd/snap /snap")
		w("fi")
		w("snap wait system seed.loaded")
		args := shQuote(m.Snap.Name)
		if m.Snap.Classic {
			args += " --classic"
		}
		if m.Snap.Channel != "" {
			args += " --channel=" + shQuote(m.Snap.Channel)
		}
		w("snap install %s", args)
	case "flatpak":
		remote := m.Flatpak.Remote
		if remote == "" {
			remote = "flathub"
		}
		w("pi_need flatpak flatpak")
		if remote == "flathub" {
			w("flatpak remote-add --system --if-not-exists flathub https://dl.flathub.org/repo/flathub.flatpakrepo")
		}
		w("flatpak install --system -y --noninteractive %s %s", shQuote(remote), shQuote(m.Flatpak.ID))
	case "tarball":
		t := m.Tarball
		w("pi_need curl curl")
		w("tmp=$(mktemp -d)")
		w("trap 'rm -rf \"$tmp\"' EXIT")
		w("curl -fsSL -o \"$tmp/archive\" %s", shQuote(t.URL))
		w("echo \"%s  $tmp/archive\" | sha256sum -c -", strings.ToLower(t.SHA256))
		w("rm -rf %s", shQuote(t.Dest))
		w("mkdir -p %s", shQuote(t.Dest))
		w("tar -xf \"$tmp/archive\" -C %s --strip-components=%d", shQuote(t.Dest), t.StripComponents)
		for _, bin := range t.Bin {
			name := bin[strings.LastIndex(bin, "/")+1:]
			w("ln -sf %s %s", shQuote(t.Dest+"/"+bin), shQuote("/usr/local/bin/"+name))
		}
	case "shell":
		b.WriteString(m.Shell.Script)
		if !strings.HasSuffix(m.Shell.Script, "\n") {
			b.WriteString("\n")
		}
	}
	return b.String()
}

func quoteAll(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = shQuote(s)
	}
	return strings.Join(q, " ")
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// ---- PowerShell ----

const psPrelude = `# Generated by PerfectImage from the app catalog. Runs as Administrator.
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
function Test-PIVerify([string]$Encoded) {
  & "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand $Encoded *> $null
  return ($LASTEXITCODE -eq 0)
}
function Invoke-PIEncoded([string]$Encoded) {
  & "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand $Encoded
  if ($LASTEXITCODE -ne 0) { throw "script exited with code $LASTEXITCODE" }
}
function Get-PIWinget {
  $cmd = Get-Command winget.exe -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  $p = Get-ChildItem "$env:ProgramFiles\WindowsApps\Microsoft.DesktopAppInstaller_*_x64__8wekyb3d8bbwe\winget.exe" -ErrorAction SilentlyContinue | Sort-Object FullName | Select-Object -Last 1
  if ($p) { return $p.FullName }
  throw 'winget is not available'
}
function Get-PIChoco {
  $exe = Join-Path $env:ProgramData 'chocolatey\bin\choco.exe'
  if (-not (Test-Path $exe)) {
    Write-Output '==> bootstrapping Chocolatey'
    Invoke-Expression ((New-Object Net.WebClient).DownloadString('https://community.chocolatey.org/install.ps1'))
  }
  if (-not (Test-Path $exe)) { throw 'Chocolatey is not available' }
  return $exe
}
function Assert-PIExit([string]$What, [int[]]$Ok = @(0)) {
  if ($Ok -notcontains $LASTEXITCODE) { throw "$What exited with code $LASTEXITCODE" }
}
function Get-PIDownload([string]$Url, [string]$Sha256, [string]$Ext) {
  $f = Join-Path $env:TEMP ([IO.Path]::GetRandomFileName() + $Ext)
  Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile $f
  $h = (Get-FileHash -Algorithm SHA256 -Path $f).Hash
  if ($h -ne $Sha256.ToUpperInvariant()) { Remove-Item -Force $f; throw "sha256 mismatch for $Url" }
  return $f
}
`

func powershellInstall(a *App, methods []Method) string {
	var b strings.Builder
	b.WriteString(psPrelude)
	fmt.Fprintf(&b, "# App: %s (%s)\n", oneLine(a.Name), a.ID)
	tag := "[" + a.ID + "]"
	verifies := uniqueVerifies(methods)
	for _, v := range verifies {
		fmt.Fprintf(&b, "if (Test-PIVerify %s) { Write-Output %s; exit 0 }\n", psQuote(psEncode(v)), psQuote("==> "+tag+" already installed"))
	}
	for i, m := range methods {
		label := fmt.Sprintf("%s method %d/%d (%s)", tag, i+1, len(methods), m.Kind())
		fmt.Fprintf(&b, "\nWrite-Output %s\ntry {\n", psQuote("==> "+label))
		for _, line := range strings.Split(strings.TrimRight(psMethod(m), "\n"), "\n") {
			b.WriteString("  " + line + "\n")
		}
		fmt.Fprintf(&b, "  if (Test-PIVerify %s) { Write-Output %s; exit 0 }\n", psQuote(psEncode(strings.TrimSpace(m.Verify))), psQuote("==> "+tag+" installed via "+m.Kind()))
		fmt.Fprintf(&b, "  Write-Output %s\n", psQuote("==> "+label+": verify failed"))
		fmt.Fprintf(&b, "} catch {\n  Write-Output (%s + $_.Exception.Message)\n}\n", psQuote("==> "+label+": install failed: "))
	}
	fmt.Fprintf(&b, "\nWrite-Output %s\nexit 1\n", psQuote("==> "+tag+" all install methods failed"))
	return b.String()
}

func powershellVerify(methods []Method) string {
	var b strings.Builder
	b.WriteString("# Exits 0 when the app is installed.\n")
	for _, v := range uniqueVerifies(methods) {
		fmt.Fprintf(&b, "& \"$env:SystemRoot\\System32\\WindowsPowerShell\\v1.0\\powershell.exe\" -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand %s *> $null\nif ($LASTEXITCODE -eq 0) { exit 0 }\n", psQuote(psEncode(v)))
	}
	b.WriteString("exit 1\n")
	return b.String()
}

func psMethod(m Method) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	switch m.Kind() {
	case "winget":
		g := m.Winget
		source := g.Source
		if source == "" {
			source = "winget"
		}
		scope := g.Scope
		if scope == "" {
			scope = "machine"
		}
		args := fmt.Sprintf("install --id %s --exact --silent --disable-interactivity --accept-package-agreements --accept-source-agreements --source %s --scope %s",
			psQuote(g.ID), psQuote(source), psQuote(scope))
		if g.Version != "" {
			args += " --version " + psQuote(g.Version)
		}
		w("$winget = Get-PIWinget")
		w("& $winget %s", args)
		// 0x8A15002B: no applicable upgrade (already installed).
		w("Assert-PIExit 'winget' @(0, -1978335189)")
	case "choco":
		args := "install " + psQuote(m.Choco.Package) + " -y --no-progress"
		if m.Choco.Version != "" {
			args += " --version " + psQuote(m.Choco.Version)
		}
		w("$choco = Get-PIChoco")
		w("& $choco %s", args)
		w("Assert-PIExit 'choco' @(0, 1641, 3010)")
	case "msi":
		args := m.MSI.Args
		if args == "" {
			args = "/qn /norestart"
		}
		w("$f = Get-PIDownload %s %s '.msi'", psQuote(m.MSI.URL), psQuote(m.MSI.SHA256))
		w("$p = Start-Process -FilePath \"$env:SystemRoot\\System32\\msiexec.exe\" -ArgumentList ('/i \"' + $f + '\" ' + %s) -Wait -PassThru", psQuote(args))
		w("Remove-Item -Force $f -ErrorAction SilentlyContinue")
		w("if (@(0, 1641, 3010) -notcontains $p.ExitCode) { throw \"msiexec exited with code $($p.ExitCode)\" }")
	case "exe":
		w("$f = Get-PIDownload %s %s '.exe'", psQuote(m.EXE.URL), psQuote(m.EXE.SHA256))
		if m.EXE.Args != "" {
			w("$p = Start-Process -FilePath $f -ArgumentList %s -Wait -PassThru", psQuote(m.EXE.Args))
		} else {
			w("$p = Start-Process -FilePath $f -Wait -PassThru")
		}
		w("Remove-Item -Force $f -ErrorAction SilentlyContinue")
		w("if (@(0, 1641, 3010) -notcontains $p.ExitCode) { throw \"installer exited with code $($p.ExitCode)\" }")
	case "powershell":
		w("Invoke-PIEncoded %s", psQuote(psEncode(m.PowerShell.Script)))
	}
	return b.String()
}
